// ===== ФУНКЦИИ РАБОТЫ СО СВИТКАМИ =====
function getScrollText(id) {
    const scroll = SCROLLS_TEXT[id];
    return scroll ? scroll.ru : '📜 Свиток ещё не написан';
}

function getScrollsCount() {
    return Object.keys(SCROLLS_TEXT).length;
}

function getScrollsProgress() {
    try {
        const saved = localStorage.getItem('coloringScrollsProgress');
        return saved ? JSON.parse(saved) : {};
    } catch(e) { return {}; }
}

function saveScrollsProgress(progress) {
    localStorage.setItem('coloringScrollsProgress', JSON.stringify(progress));
    if (typeof saveState === 'function') saveState();
}

function isScrollUnlocked(id) {
    const progress = getScrollsProgress();
    return progress[id] === true;
}

function buyScroll(id) {
    if (isScrollUnlocked(id)) {
        return { success: false, message: 'Свиток уже куплен' };
    }
    if (appState.totalPoints < 10) {
        return { success: false, message: 'Недостаточно звёзд (нужно 10)' };
    }
    appState.totalPoints -= 10;
    const progress = getScrollsProgress();
    progress[id] = true;
    saveScrollsProgress(progress);
    saveState();
    return { success: true, message: 'Свиток куплен!' };
}

